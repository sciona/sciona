def build_decomposed_vsb_graph():
    nodes=[];edges=[]
    for name,operation,bindings in STAGES:
        inputs,outputs=PORTS[operation]
        runtime='sciona.atoms.scipy.signal.lfilter' if operation=='lfilter' else 'sciona.atoms.ml.decomposed_vsb_execution.'+operation
        ports=[IOSpec(name=n,type_desc=t) for n,t in inputs]
        if operation=='lfilter':
            for p in ports:
                if p.name in ('axis','zi'):
                    p.required=False;p.default_value_repr='-1' if p.name=='axis' else 'None'
        nodes.append(AlgorithmicNode(node_id=name,name=name,description='Explicit '+operation.replace('_',' '),
            concept_type='custom',status=NodeStatus.ATOMIC,matched_primitive=runtime,
            inputs=ports,outputs=[IOSpec(name=n,type_desc=t) for n,t in outputs]))
        for port,kind in inputs:
            if port not in bindings:continue
            source,output=bindings[port];callable_input=port.endswith('_function')
            edges.append(DependencyEdge(source_id=source,target_id=name,output_name=output,input_name=port,
                source_type='object' if callable_input else kind,target_type=kind,
                edge_kind=EdgeKind.CALLABLE_INJECTION if callable_input else EdgeKind.DATA_FLOW))
    return CDGExport(nodes=nodes,edges=edges,metadata=dict(
        artifact_source='complete_original_competition_reconstruction',publication_status='draft',
        source_version_id='d79e40e4-45b0-5e74-a83c-c68c91f12afb',
        catalog_output_sources={'result':dict(node_id='encode_result',output_name='result')},
        num_nodes=len(nodes),num_edges=len(edges),
        scope='Complete independent baseline, peak, descriptor and phase aggregation; 125 tree models, count-preserving score aggregation, signal-label threshold and strict triple decisions.',
        reuse_boundary='Published generic lfilter is bound explicitly. Numeric feature and generic-width fold operations are separately selectable. Consecutive triples, nine-feature order and five-way fold coverage remain explicit recipe policy.',
        limits=['Both heldouts influence early stopping and threshold fitting uses in-training scores.',
                'No historical accuracy, unbiased validation or notebook code reuse claim.',
                'Exact registered bindings and matching feature provenance are required.',
                'Full graph qualification and original publication remain pending.']))
